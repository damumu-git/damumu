"""Create file://-safe App preview fonts from the same assets used by Flutter.

Requires fonttools[woff]. Font sources and licenses are documented in FONTS.md.
No glyphs are removed; WOFF2 is a reversible font container conversion.
"""
from base64 import b64encode
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from shutil import copyfile

from fontTools.ttLib import TTFont
from fontTools.ttLib.woff2 import WOFF2FlavorData
import brotli

# Moderate Brotli compression keeps large CJK font rebuilds practical. WOFF2's
# null transforms preserve the original outlines and variable-font tables.
_compress = brotli.compress


def compress_preview(data, **options):
    options.setdefault("quality", 6)
    return _compress(data, **options)


brotli.compress = compress_preview

HERE = Path(__file__).resolve().parent
FONTS = HERE.parents[1] / "app" / "assets" / "fonts"
SOURCES = [
    ("YsabeauOffice-VF.ttf", "Ysabeau Office", "1 1000"),
    ("LXGWWenKaiLite-Regular.ttf", "LXGW WenKai Lite", "400"),
    ("LXGWWenKaiLite-Medium.ttf", "LXGW WenKai Lite", "500"),
    ("LXGWWenKaiKR-Regular.ttf", "LXGW WenKai KR", "400"),
    ("LXGWWenKaiKR-Medium.ttf", "LXGW WenKai KR", "500"),
    ("NotoSansKR-VF.ttf", "Noto Sans KR", "100 900"),
]

css = ["/* Generated by build-fonts.py from licensed local Flutter assets. */"]
for filename, family, weight in SOURCES:
    source = FONTS / filename
    font = TTFont(source, recalcTimestamp=False, recalcBBoxes=False)
    original_cmap = font.getBestCmap()
    font.flavor = "woff2"
    font.flavorData = WOFF2FlavorData(transformedTables=set())
    output = BytesIO()
    font.save(output)
    packed = output.getvalue()
    # Check that container conversion has retained the complete Unicode mapping.
    restored = TTFont(BytesIO(packed))
    assert restored.getBestCmap() == original_cmap
    assert restored.reader["glyf"] == font.reader["glyf"]
    assert restored["OS/2"].usWeightClass == font["OS/2"].usWeightClass
    css.append(f"/* {filename}: sha256 {sha256(source.read_bytes()).hexdigest()} */")
    css.append(
        f"@font-face {{font-family:'{family}';font-style:normal;font-weight:{weight};"
        f"font-display:swap;src:url(data:font/woff2;base64,{b64encode(packed).decode()}) format('woff2');}}"
    )
    print(f"{filename}: WOFF2 {len(packed):,} bytes, {len(original_cmap):,} characters retained", flush=True)

css.append(
    ":root {font-family:'Ysabeau Office','LXGW WenKai Lite','LXGW WenKai KR','Noto Sans KR','Segoe UI',"
    "'Microsoft YaHei',sans-serif;font-synthesis:none;}"
)
(HERE / "app-fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
(HERE / "licenses").mkdir(exist_ok=True)
for filename in ["LXGWWenKai-LICENSE.txt", "LXGWWenKaiKR-LICENSE.txt", "YsabeauOffice-LICENSE.txt", "NotoSansKR-LICENSE.txt"]:
    copyfile(FONTS / filename, HERE / "licenses" / filename)
