"""Export self-hosted Admin WOFF2 from the validated, same-source App preview.

Standard-library only. First rebuild preview/app/build-fonts.py when changing
upstream fonts; normal Admin/Docker builds use the committed files directly.
"""
import base64
import hashlib
from pathlib import Path
import re
import shutil

here = Path(__file__).resolve().parent
repo = here.parent
source = (repo / "preview/app/app-fonts.css").read_text(encoding="utf-8")
pattern = re.compile(
    r"/\* ([\w.-]+\.ttf): sha256 ([0-9a-f]{64}) \*/\s*"
    r"@font-face \{font-family:'([^']+)';font-style:normal;font-weight:([^;]+);"
    r"font-display:swap;src:url\(data:font/woff2;base64,([A-Za-z0-9+/=]+)\) format\('woff2'\);\}"
)
faces = pattern.findall(source)
assert len(faces) == 6, "Expected complete App typography stack"
destination = here / "src/assets/fonts"
destination.mkdir(parents=True, exist_ok=True)
css = ["/* Generated by build-fonts.py; sources and OFL licenses: admin/FONTS.md. */"]
for filename, digest, family, weight, encoded in faces:
    original = repo / "app/assets/fonts" / filename
    assert hashlib.sha256(original.read_bytes()).hexdigest() == digest, filename
    packed = base64.b64decode(encoded, validate=True)
    assert packed[:4] == b"wOF2"
    name = Path(filename).with_suffix(".woff2").name
    (destination / name).write_bytes(packed)
    css += [f"/* {filename}: sha256 {digest} */",
            f"@font-face {{font-family:'{family}';font-style:normal;font-weight:{weight};"
            f"font-display:swap;src:url('./assets/fonts/{name}') format('woff2');}}"]
    print(f"{name}: {len(packed):,} bytes")
(here / "src/fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
licenses = here / "public/licenses/fonts"
licenses.mkdir(parents=True, exist_ok=True)
for filename in ["LXGWWenKai-LICENSE.txt", "LXGWWenKaiKR-LICENSE.txt",
                 "YsabeauOffice-LICENSE.txt", "NotoSansKR-LICENSE.txt"]:
    shutil.copyfile(repo / "app/assets/fonts" / filename, licenses / filename)
