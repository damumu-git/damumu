"""Build self-hosted Admin sans-serif fonts and file-safe offline preview fonts.
Requires fonttools[woff]; release/Docker builds use committed assets directly.
"""
import base64
import hashlib
from io import BytesIO
from pathlib import Path
import shutil
import brotli
from fontTools.ttLib import TTFont
from fontTools.ttLib.woff2 import WOFF2FlavorData

here = Path(__file__).resolve().parent
repo = here.parent
source = repo / "app/assets/fonts"
destination = here / "src/assets/fonts"
destination.mkdir(parents=True, exist_ok=True)
compress = brotli.compress
brotli.compress = lambda data, **kwargs: compress(data, **({"quality": 6} | kwargs))
faces = [("NotoSansSC-VF.ttf", "Noto Sans SC"), ("NotoSansKR-VF.ttf", "Noto Sans KR")]
css = ["/* Generated by admin/build-fonts.py; OFL sources: admin/FONTS.md. */"]
preview = ["/* Same complete Unicode mapping as production Admin fonts. */"]
for filename, family in faces:
    original = source / filename
    font = TTFont(original, recalcTimestamp=False, recalcBBoxes=False)
    axis = next(a for a in font["fvar"].axes if a.axisTag == "wght")
    weight = f"{axis.minValue:g} {axis.maxValue:g}"
    cmap = font.getBestCmap()
    font.flavor = "woff2"
    font.flavorData = WOFF2FlavorData(transformedTables=set())
    output = BytesIO()
    font.save(output)
    packed = output.getvalue()
    restored = TTFont(BytesIO(packed))
    assert restored.getBestCmap() == cmap
    assert restored.reader["glyf"] == font.reader["glyf"]
    assert restored["OS/2"].usWeightClass == font["OS/2"].usWeightClass
    assert [(a.axisTag, a.minValue, a.maxValue) for a in restored["fvar"].axes] == [(a.axisTag, a.minValue, a.maxValue) for a in font["fvar"].axes]
    name = Path(filename).with_suffix(".woff2").name
    (destination / name).write_bytes(packed)
    comment = f"/* {filename}: sha256 {hashlib.sha256(original.read_bytes()).hexdigest()} */"
    head = f"@font-face {{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:swap;"
    css += [comment, head + f"src:url('./assets/fonts/{name}') format('woff2');}}"]
    preview += [comment, head + f"src:url(data:font/woff2;base64,{base64.b64encode(packed).decode()}) format('woff2');}}"]
    print(f"{name}: {len(packed):,} bytes, {len(cmap):,} characters retained, weights {weight}")
(here / "src/fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
preview += [':root {font-family:"Noto Sans SC","Noto Sans KR","Segoe UI","Microsoft YaHei",system-ui,sans-serif;font-synthesis:none;}']
(repo / "preview/admin/admin-fonts.css").write_text("\n".join(preview) + "\n", encoding="utf-8")
for folder in [here / "public/licenses/fonts", repo / "preview/admin/licenses"]:
    folder.mkdir(parents=True, exist_ok=True)
    for name in ["NotoSansSC-LICENSE.txt", "NotoSansKR-LICENSE.txt"]:
        shutil.copyfile(source / name, folder / name)
